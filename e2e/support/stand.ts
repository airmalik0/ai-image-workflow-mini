/**
 * Настройки стенда, общие для подъёма окружения и самих тестов.
 *
 * Держать их в одном модуле обязательно: сценарий «нода упала → Retry» работает,
 * только если стенд поднят с той же нодой в `FAKE_FAIL_NODES`, которую проверяет
 * тест. Разъехавшись, эти два места дали бы зелёный прогон на неверном стенде
 * или загадочный отказ вместо внятной причины.
 */

/** Нода, на которой заглушке велено падать. В сценарии «Редактирование» она одна. */
export const FAILING_NODE = 'editImage-1'

/**
 * `:1` — падает только первая попытка в каждом запуске. Повтор той же ноды
 * проходит, а следующий запуск снова начинается с ошибки, поэтому сценарий
 * воспроизводится сколько угодно раз подряд.
 */
export const FAKE_FAIL_NODES = `${FAILING_NODE}:1`

/** Провайдер стенда: живой ключ для e2e не нужен и не должен требоваться. */
export const IMAGE_PROVIDER = 'fake'

export const BASE_URL = process.env['E2E_BASE_URL'] ?? 'http://localhost:3000'

/**
 * Свой стенд поднимаем сами. Если адрес задан снаружи (dev-сервер Vite, публичное
 * демо), окружение уже чьё-то — трогать его нельзя.
 */
export const OWNS_STACK = process.env['E2E_BASE_URL'] === undefined
